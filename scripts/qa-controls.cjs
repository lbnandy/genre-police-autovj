"use strict";
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto'), assert = require('node:assert/strict');
const {_electron} = require(process.env.AUTOVJ_PLAYWRIGHT || 'playwright');
const {Library, atomicJson} = require('../packages/library.cjs');
const {select} = require('./qa-picker.cjs');
const ROOT = path.resolve(__dirname, '..'), OUT = path.join(ROOT, 'output/playwright/controls');
(async () => {
  fs.mkdirSync(OUT, {recursive: true});
  const data = path.join(ROOT, '.qa', 'controls-' + crypto.randomUUID()), id = crypto.randomUUID(), trackId = crypto.randomUUID();
  const library = new Library(path.join(data, 'libraries', id));
  library.upsert({id: trackId, title: 'Midnight City 夜空の音楽 밤하늘', artist: 'AutoVJ 字体確認', manualGenre: 'techno', status: 'ready'});
  atomicJson(path.join(data, 'app.json'), {activeLibrary: id});
  const env = {...process.env, AUTOVJ_DATA_DIR: data}; delete env.ELECTRON_RUN_AS_NODE;
  const launch = () => _electron.launch({executablePath: path.join(ROOT, 'node_modules/electron/dist/electron.exe'), args: [ROOT, '--lang=zh-CN'], env});
  let app = await launch();
  const errors = [], fonts = [];
  try {
    let page = app.windows().find(p => p.url().includes('console.html')) || await app.waitForEvent('window', {predicate: p => p.url().includes('console.html')});
    await page.waitForSelector("#layout-button", {state:"attached"});
    const stage = app.windows().find(p => p.url().includes('stage.html'));
    for (const p of app.windows()) p.on('pageerror', e => errors.push(e.message));
    assert.equal(await page.locator('#english-condensed').isChecked(), false);
    for (const lang of ['zh', 'en', 'ja', 'ko']) {
      await page.evaluate(lang => window.autovj.call('settings', {language: lang}), lang);
      await stage.waitForFunction(() => document.body.dataset.standby === 'true');
      assert.equal(await stage.locator('#genre-face').innerText(), 'STANDBY');
    }
    await page.evaluate(() => window.autovj.call('settings', {language: 'zh'}));
    await page.waitForFunction(() => document.documentElement.lang === 'zh-CN');
    await page.locator('[data-tab=settings]').click();
    await page.locator('#layout-button').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#layout-button').getAttribute('aria-expanded'), 'true');
    await page.keyboard.press('End');
    await page.keyboard.press('Enter');
    await stage.waitForFunction(() => document.body.dataset.fullscreenLayout === 'stacked');
    await page.locator('#layout-button').press('Enter');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#layout-button').getAttribute('aria-expanded'), 'false');
    assert.equal(await page.locator('#layout-button').evaluate(el => el === document.activeElement), true);
    await page.locator('[data-tab=live]').click();
    await page.locator('#lock-theme-button').click();
    await page.keyboard.type('b');
    assert.equal((await page.evaluate(() => window.autovj.call('state'))).live.blackout, false, 'Picker typing must not trigger blackout');
    await page.keyboard.press('Escape');
    await stage.setViewportSize({width: 1440, height: 1080});
    await stage.waitForTimeout(1400);
    assert.equal(await stage.locator('#genre-face').evaluate(el => getComputedStyle(el).filter), 'none');
    assert.equal(await stage.locator('#app').evaluate(el => getComputedStyle(el).filter), 'none');
    await stage.screenshot({path: path.join(OUT, 'standby-stacked-1440x1080.png')});
    await page.locator('[data-tab=settings]').click();
    await page.locator('#english-condensed').check();
    await stage.waitForFunction(() => document.body.dataset.fullscreenEnglish === 'condensed');
    await page.locator('#text-visible').uncheck();
    await stage.waitForFunction(() => document.body.dataset.stageOutputText === 'false');
    assert.equal(await stage.locator('#hud').isVisible(), false);
    await page.locator('#text-visible').check();
    await page.evaluate(id => window.autovj.call('preview-track', id), trackId);
    await stage.waitForFunction(() => document.body.dataset.standby === 'false');
    const cdp = await stage.context().newCDPSession(stage);
    await cdp.send('DOM.enable'); await cdp.send('CSS.enable');
    for (const condensed of [true, false]) {
      await page.locator('#english-condensed').setChecked(condensed);
      await stage.waitForFunction(value => document.body.dataset.fullscreenEnglish === value, condensed ? 'condensed' : 'regular');
      await stage.evaluate(() => document.fonts.ready);
      await stage.waitForTimeout(200);
      const {root} = await cdp.send('DOM.getDocument');
      const {nodeId} = await cdp.send('DOM.querySelector', {nodeId: root.nodeId, selector: '.title-scroll-text'});
      const result = await cdp.send('CSS.getPlatformFontsForNode', {nodeId});
      assert.ok(result.fonts.some(f => f.familyName.includes(condensed ? 'Barlow Condensed' : 'DM Sans')), JSON.stringify(result));
      assert.ok(result.fonts.some(f => f.familyName.includes('Noto Sans')), JSON.stringify(result));
      fonts.push({condensed, ...result});
    }
    await page.locator('[data-tab=settings]').click();
    await page.locator('#language-button').click();
    const menuBounds = await page.locator('#language-menu').boundingBox();
    assert.ok(menuBounds && menuBounds.y + menuBounds.height <= (await page.viewportSize()?.height || 940));
    await page.screenshot({path: path.join(OUT, 'settings-language-menu.png')});
    await page.locator('h1').filter({hasText: '设置'}).click();
    assert.equal(await page.locator('#language-button').getAttribute('aria-expanded'), 'false');
    await page.locator('[data-action=new-preset]').click();
    await page.locator('#preset-name').fill('QA custom preset');
    await select(page, 'preset-base', 'techno');
    await page.locator('#preset-base-button').click();
    await page.screenshot({path: path.join(OUT, 'dialog-visual-menu.png')});
    await page.keyboard.press('Escape');
    await page.locator('[data-action=save-preset]').click();
    await page.locator('#preset-dialog').waitFor({state: 'hidden'});
    assert.ok((await page.evaluate(() => window.autovj.call('state'))).library.themes.some(x => x.label === 'QA custom preset'));
    await page.locator('[data-tab=live]').click();
    await page.evaluate(() => window.autovj.call('lock', null));
    await app.evaluate(({BrowserWindow}) => {
      BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('console.html')).setSize(1920, 1080);
    });
    await stage.setViewportSize({width: 1920, height: 1080});
    await page.waitForFunction(() => document.querySelector('#preview').naturalWidth > 760);
    const preview = await page.locator('#preview').evaluate(el => ({width: el.naturalWidth, height: el.naturalHeight, cssWidth: el.clientWidth, dpr: devicePixelRatio}));
    await page.locator('#english-condensed').check();
    await page.mouse.move(0, 400);
    await page.waitForTimeout(1200);
    await page.locator('[data-tab=live]').click();
    await page.screenshot({path: path.join(OUT, 'live-controls.png')});
    assert.deepEqual(errors, []);
    await app.close(); app = await launch();
    page = app.windows().find(p => p.url().includes('console.html')) || await app.waitForEvent('window', {predicate: p => p.url().includes('console.html')});
    await page.waitForSelector("#english-condensed", {state:"attached"});
    assert.equal(await page.locator('#english-condensed').isChecked(), true, 'Font preference survives restart');
    assert.equal(await page.locator('#layout').inputValue(), 'stacked');
    fs.writeFileSync(path.join(OUT, 'report.json'), JSON.stringify({passed: true, fonts, preview, errors}, null, 2));
    console.log('Controls QA passed: keyboard, dialogs, four standby languages, actual font faces, adaptive preview, persistence.');
  } finally { await app.close(); }
})().catch(e => {console.error(e); process.exitCode = 1;});
